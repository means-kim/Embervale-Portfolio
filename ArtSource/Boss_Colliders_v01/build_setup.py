"""Generate the reviewed collider curves as an in-memory Unity C# setup command.

Run with Python, then execute setup-command.cs through Unity MCP execute_code.
Coordinates are local Unity units, using the sprites' PPU 50 and bottom-center pivot.
This file does not modify Unity assets itself.
"""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
clips = json.loads((HERE / 'clips-before.json').read_text())
names = ['Hurtbox', 'SlamHitbox', 'SwingHitbox', 'ChargeHitbox']
# x, y, width, height, rotation Z (degrees)
defaults = [[0, 2.95, 5.6, 5.6, 0], [-3.5, .7, 1.9, 1.3, 0],
            [-1.15, 3.45, 5.45, 1.55, 13], [-1.45, 2.7, 3.7, 4.8, 0]]

def poses(sprite):
    action, index = sprite.rsplit('_', 1)
    i = int(index)
    boxes = [v[:] for v in defaults]
    active = [1, 0, 0, 0]
    if action == 'Boss_Death':
        active = [0, 0, 0, 0]
    elif action == 'Boss_Hit' and i < 3:
        boxes[0] = [.45, 3.05, 5.4, 5.8, 0]
    elif action == 'Boss_Slam':
        if 4 <= i <= 6:
            boxes[0] = [-.15, 2.55, 5.6, 4.8, 0]
        if i == 4:
            active[1] = 1
            boxes[1] = [-3.45, 4.65, 1.65, 2.0, -32]
        elif i == 5:
            active[1] = 1
            boxes[1] = [-3.65, .7, 1.9, 1.3, 0]
    elif action == 'Boss_Swing':
        if i == 2:
            boxes[0][0] -= .34
        if i in (4, 5):
            active[2] = 1
            boxes[2] = ([-1.15, 3.45, 5.45, 1.55, 13] if i == 4 else
                        [-1.6, 3.55, 5.5, 1.55, 8])
    elif action == 'Boss_Charge':
        if i in (1, 2, 9):
            boxes[0] = [-.25, 2.25, 5.4, 4.3, 0]
        elif 3 <= i <= 8:
            boxes[0] = [-.3, 2.5, 5.7, 4.7, 0]
        elif i == 10:
            boxes[0] = [0, 2.7, 5.6, 5.1, 0]
        if 3 <= i <= 7:
            active[3] = 1
            boxes[3] = [-1.5, 2.6, 3.7, 4.6, 0]
            if i == 5:
                boxes[3] = [-1.4, 2.5, 3.7, 4.5, 0]
            elif i == 7:
                boxes[3] = [-1.5, 2.8, 3.7, 4.4, 0]
    return [dict(zip(['x', 'y', 'width', 'height', 'rotation', 'enabled'],
                     box + [on]), name=name) for name, box, on in zip(names, boxes, active)]

review = []
for clip in clips:
    frames = [dict(key, boxes=poses(key['sprite'])) for key in clip['keys']]
    review.append(dict(clip, frames=frames))
(HERE / 'collider-layout.json').write_text(json.dumps(review, indent=2) + '\n')

code = '''// Generated by build_setup.py. Back up before first execution.
if (Application.isPlaying) throw new System.Exception("Exit Play Mode first.");
var scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
if (scene.name != "MinsuScene") throw new System.Exception("Expected MinsuScene.");
var boss = GameObject.Find("Boss_SnowGiant");
if (boss == null) throw new System.Exception("Boss not found.");
var layer = LayerMask.NameToLayer("Boss");
if (layer < 0) throw new System.Exception("Boss layer missing.");
var prefabPath = "Assets/03.Prefabs/Boss/Boss_SnowGiant.prefab";
var root = UnityEditor.PrefabUtility.LoadPrefabContents(prefabPath);
try {
    root.tag = "Boss";
    root.layer = layer;
    var old = root.transform.Find("Colliders");
    if (old != null) throw new System.Exception("Collider rig already exists; inspect before re-running.");
    var group = new GameObject("Colliders");
    group.transform.SetParent(root.transform, false);
    group.tag = "Boss";
    group.layer = layer;
    var rb = root.GetComponent<Rigidbody2D>();
    if (rb == null) rb = root.AddComponent<Rigidbody2D>();
    rb.bodyType = RigidbodyType2D.Kinematic;
    rb.gravityScale = 0f;
    rb.constraints = RigidbodyConstraints2D.FreezeRotation;
    rb.interpolation = RigidbodyInterpolation2D.Interpolate;
    var rig = root.AddComponent<BossColliderRig>();
    var serial = new UnityEditor.SerializedObject(rig);
    serial.FindProperty("spriteRenderer").objectReferenceValue = root.GetComponent<SpriteRenderer>();
    serial.FindProperty("facingRoot").objectReferenceValue = group.transform;
    serial.FindProperty("health").objectReferenceValue = root.GetComponent<Health>();
'''
for name, shape in zip(names, defaults):
    x, y, w, h, z = shape
    field = name[0].lower() + name[1:]
    code += f'''    {{
        var obj = new GameObject("{name}");
        obj.transform.SetParent(group.transform, false);
        obj.tag = "Boss"; obj.layer = layer;
        obj.transform.localPosition = new Vector3({x}f, {y}f, 0f);
        obj.transform.localRotation = Quaternion.Euler(0f, 0f, {z}f);
        var box = obj.AddComponent<BoxCollider2D>();
        box.isTrigger = true;
        box.size = new Vector2({w}f, {h}f);
        box.enabled = {'true' if name == 'Hurtbox' else 'false'};
        serial.FindProperty("{field}").objectReferenceValue = box;
    }}
'''
code += '''    serial.ApplyModifiedPropertiesWithoutUndo();
    UnityEditor.PrefabUtility.SaveAsPrefabAsset(root, prefabPath);
} finally {
    UnityEditor.PrefabUtility.UnloadPrefabContents(root);
}
UnityEditor.Undo.SetCurrentGroupName("Set up Snow Giant animation colliders");
foreach (var name in new[] { "BodyHitBox", "LeftArm", "RightHand" }) {
    var child = boss.transform.Find(name);
    if (child != null) UnityEditor.Undo.DestroyObjectImmediate(child.gameObject);
}
// Do not apply the whole scene instance: preserve unrelated user overrides.
var written = new System.Collections.Generic.List<string>();
'''
props = [('Transform', 'm_LocalPosition.x', 'x'),
         ('Transform', 'm_LocalPosition.y', 'y'),
         ('Transform', 'localEulerAnglesRaw.z', 'rotation'),
         ('BoxCollider2D', 'm_Size.x', 'width'),
         ('BoxCollider2D', 'm_Size.y', 'height'),
         ('BoxCollider2D', 'm_Enabled', 'enabled')]
for clip in review:
    code += f'{{\nvar clip = UnityEditor.AssetDatabase.LoadAssetAtPath<AnimationClip>("{clip["path"]}");\n'
    code += 'UnityEditor.Undo.RegisterCompleteObjectUndo(clip, "Add boss collider curves");\n'
    for bi, name in enumerate(names):
        for typ, prop, key in props:
            values = []
            for frame in clip['frames']:
                value = frame['boxes'][bi][key]
                if not values or values[-1][1] != value:
                    values.append((frame['time'], value))
            keys = ','.join(f'new Keyframe({t:.9f}f,{v}f)' for t, v in values)
            code += f'''{{
var binding = UnityEditor.EditorCurveBinding.FloatCurve("Colliders/{name}", typeof({typ}), "{prop}");
var curve = new AnimationCurve(new[] {{ {keys} }});
for (int k = 0; k < curve.length; k++) {{
    UnityEditor.AnimationUtility.SetKeyLeftTangentMode(curve, k, UnityEditor.AnimationUtility.TangentMode.Constant);
    UnityEditor.AnimationUtility.SetKeyRightTangentMode(curve, k, UnityEditor.AnimationUtility.TangentMode.Constant);
}}
UnityEditor.AnimationUtility.SetEditorCurve(clip, binding, curve);
}}
'''
    code += 'UnityEditor.EditorUtility.SetDirty(clip);\nUnityEditor.AssetDatabase.SaveAssetIfDirty(clip);\nwritten.Add(clip.name);\n}\n'
code += '''UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
return new { prefab = prefabPath, clips = written, sceneDirty = scene.isDirty,
    childCount = boss.transform.childCount,
    colliderCount = boss.GetComponentsInChildren<Collider2D>(true).Length };
'''
(HERE / 'setup-command.cs').write_text(code)
commands = HERE / 'Commands'
commands.mkdir(exist_ok=True)
rig_code, clip_code = code.split('var written = new System.Collections.Generic.List<string>();', 1)
(commands / '00-rig.cs').write_text(rig_code + '\nUnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);\nreturn boss.GetComponentsInChildren<Collider2D>(true).Length;\n')
import re
chunks = re.split(r'(?=\{\nvar clip = UnityEditor.AssetDatabase.LoadAssetAtPath)', clip_code)[1:]
for i in range(0, len(chunks), 2):
    part = ''.join(chunks[i:i+2]).split('UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);')[0]
    (commands / f'{i//2+1:02d}-clips.cs').write_text('var written = new System.Collections.Generic.List<string>();\n' + part + '\nreturn written;\n')
print('Prepared setup for', len(review), 'clips and 4 colliders.')
